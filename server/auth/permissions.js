export const PERMISSIONS = MODULES.flatMap((module, moduleIndex) =>
  module.actions.map((action, actionIndex) => ({
    key: `${module.key}.${action}`,
    module: module.key,
    action,
    label: `${module.label}: ${ACTION_LABELS[action] || action}`,
    sort_order: moduleIndex * 100 + actionIndex,
  })),
);

export const PERMISSION_KEYS = PERMISSIONS.map((permission) => permission.key);

export const PERMISSION_MODULES = MODULES.map((module) => ({
  key: module.key,
  label: module.label,
  group: module.group,
  actions: module.actions.map((action) => ({
    key: action,
    label: ACTION_LABELS[action] || action,
    permission: `${module.key}.${action}`,
  })),
}));

export const PERMISSION_GROUPS = GROUPS.map((group) => ({
  ...group,
  modules: PERMISSION_MODULES.filter((module) => module.group === group.key),
}));

function viewOnlyKeys() {
  return PERMISSION_KEYS.filter((key) => key.endsWith('.view'));
}

