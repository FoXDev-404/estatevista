-- 1. Create properties table
CREATE TABLE IF NOT EXISTS public.properties (
    id VARCHAR(32) PRIMARY KEY,
    slug VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    price NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',
    location JSONB NOT NULL DEFAULT '{}'::jsonb,
    specifications JSONB NOT NULL DEFAULT '{}'::jsonb,
    images JSONB NOT NULL DEFAULT '[]'::jsonb,
    description TEXT NOT NULL DEFAULT '',
    amenities JSONB NOT NULL DEFAULT '[]'::jsonb,
    facilities JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(30) NOT NULL DEFAULT 'available',
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    trending BOOLEAN NOT NULL DEFAULT FALSE,
    created_at VARCHAR(30) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Performance indexes
CREATE INDEX IF NOT EXISTS idx_properties_slug ON public.properties (slug);
CREATE INDEX IF NOT EXISTS idx_properties_type ON public.properties (type);
CREATE INDEX IF NOT EXISTS idx_properties_purpose ON public.properties (purpose);
CREATE INDEX IF NOT EXISTS idx_properties_status ON public.properties (status);
CREATE INDEX IF NOT EXISTS idx_properties_price ON public.properties (price);
CREATE INDEX IF NOT EXISTS idx_properties_city ON public.properties ((location->>'city'));
CREATE INDEX IF NOT EXISTS idx_properties_area ON public.properties ((location->>'area'));
CREATE INDEX IF NOT EXISTS idx_properties_featured ON public.properties (featured);
CREATE INDEX IF NOT EXISTS idx_properties_trending ON public.properties (trending);

-- 3. Create enquiries & contact messages table
CREATE TABLE IF NOT EXISTS public.enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(32) REFERENCES public.properties(id) ON DELETE SET NULL,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(50) NOT NULL,
    subject VARCHAR(255),
    message TEXT NOT NULL,
    type VARCHAR(30) NOT NULL DEFAULT 'general', -- 'general' or 'property'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_enquiries_property_id ON public.enquiries (property_id);
CREATE INDEX IF NOT EXISTS idx_enquiries_created_at ON public.enquiries (created_at DESC);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.properties ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.enquiries ENABLE ROW LEVEL SECURITY;

-- 5. RLS Policies
-- Allow anyone (public anon) to read available properties
DROP POLICY IF EXISTS "Public can view properties" ON public.properties;
CREATE POLICY "Public can view properties"
    ON public.properties FOR SELECT
    USING (true);

-- Allow backend service role full access to properties
DROP POLICY IF EXISTS "Service role full access on properties" ON public.properties;
CREATE POLICY "Service role full access on properties"
    ON public.properties FOR ALL
    USING (true)
    WITH CHECK (true);

-- Allow public to submit contact messages and enquiries
DROP POLICY IF EXISTS "Public can insert enquiries" ON public.enquiries;
CREATE POLICY "Public can insert enquiries"
    ON public.enquiries FOR INSERT
    WITH CHECK (true);

-- Allow service role full access on enquiries
DROP POLICY IF EXISTS "Service role full access on enquiries" ON public.enquiries;
CREATE POLICY "Service role full access on enquiries"
    ON public.enquiries FOR ALL
    USING (true)
    WITH CHECK (true);

