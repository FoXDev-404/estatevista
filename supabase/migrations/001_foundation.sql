-- ====================================================================
-- EstateVista foundation schema (Release 1)
-- ====================================================================
-- Applied after supabase/schema.sql (the legacy properties/enquiries base).
-- Every statement is idempotent so the file can be re-run safely.
--
-- Security model:
--   * The API server uses the Supabase service-role key and enforces
--     company scoping in application code.
--   * RLS is enabled on every new table. No anon/authenticated policies
--     are created, so the public API keys cannot read these tables.
-- ====================================================================

create extension if not exists pgcrypto;

-- 1. Companies -------------------------------------------------------
create table if not exists public.companies (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  legal_name text,
  registration_number text,
  tax_number text,
  email text,
  phone text,
  address text,
  city text,
  state text,
  postal_code text,
  country text default 'United States',
  logo_path text,
  favicon_path text,
  currency text not null default 'USD',
  timezone text not null default 'UTC',
  date_format text not null default 'YYYY-MM-DD',
  number_decimals integer not null default 2 check (number_decimals between 0 and 3),
  is_active boolean not null default true,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Branches --------------------------------------------------------
create table if not exists public.branches (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null,
  code text not null,
  phone text,
  email text,
  address text,
  manager_id uuid,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, code)
);

-- 3. Users -----------------------------------------------------------
create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  branch_id uuid references public.branches(id) on delete set null,
  name text not null,
  email text not null,
  password_hash text not null,
  phone text,
  avatar_path text,
  full_access boolean not null default false,
  is_active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, email)
);

-- The branch manager is a user, and a user belongs to a branch. Add the
-- second half of the cycle after both tables exist.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'branches_manager_id_fkey'
      and conrelid = 'public.branches'::regclass
  ) then
    alter table public.branches
      add constraint branches_manager_id_fkey
      foreign key (manager_id) references public.users(id) on delete set null;
  end if;
end $$;

