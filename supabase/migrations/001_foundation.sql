-- 10. Helpers --------------------------------------------------------
-- Atomically consume the next company-scoped document number.
create or replace function public.next_document_number(
  p_company_id uuid,
  p_document_type text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  seq public.number_sequences%rowtype;
  current_year integer := extract(year from now());
  current_month integer := extract(month from now());
  next_val bigint;
begin
  select * into seq
  from public.number_sequences
  where company_id = p_company_id and document_type = p_document_type
  for update;

  if not found then
    raise exception 'Number sequence % is not configured for this company', p_document_type;
  end if;

  if seq.reset_period = 'yearly' and seq.last_year is distinct from current_year then
    next_val := 1;
  elsif seq.reset_period = 'monthly'
        and (seq.last_year is distinct from current_year or seq.last_month is distinct from current_month) then
    next_val := 1;
  else
    next_val := seq.next_value;
  end if;

  update public.number_sequences
  set next_value = next_val + 1,
      last_year = current_year,
      last_month = current_month,
      updated_at = now()
  where id = seq.id;

  if seq.reset_period = 'yearly' then
    return seq.prefix || current_year::text || '-' || lpad(next_val::text, seq.padding, '0');
  elsif seq.reset_period = 'monthly' then
    return seq.prefix || to_char(now(), 'YYYYMM') || '-' || lpad(next_val::text, seq.padding, '0');
  end if;

  return seq.prefix || lpad(next_val::text, seq.padding, '0');
end;
$$;

-- Permission lookup used by the session middleware.
create or replace function public.user_permission_keys(p_user_id uuid)
returns table (permission_key text)
language sql
security definer
set search_path = public
as $$
  select distinct p.key
  from public.user_roles ur
  join public.role_permissions rp on rp.role_id = ur.role_id
  join public.permissions p on p.id = rp.permission_id
  where ur.user_id = p_user_id
  order by p.key;
$$;

revoke all on function public.next_document_number(uuid, text) from public;
revoke all on function public.user_permission_keys(uuid) from public;
grant execute on function public.next_document_number(uuid, text) to service_role;
grant execute on function public.user_permission_keys(uuid) to service_role;

